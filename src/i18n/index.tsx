const LANGUAGE_STORAGE_KEY = "playhome.language";

function isLanguageCode(value: string): value is LanguageCode {
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(value);
}

export function detectLanguage(): LanguageCode {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored && isLanguageCode(stored)) return stored;
  } catch {
    // Storage can be blocked in private browsing; system detection still works.
  }

  const candidates =
    typeof navigator !== "undefined" && navigator.languages?.length
      ? navigator.languages
      : typeof navigator !== "undefined"
        ? [navigator.language]
        : [];

  for (const candidate of candidates) {
    const normalized = candidate.replace("_", "-").toLowerCase();
    const exact = SUPPORTED_LANGUAGES.find((code) => code.toLowerCase() === normalized);
    if (exact) return exact;

    if (normalized === "pt-br" || normalized === "pt") return "pt";
    if (normalized.startsWith("pt-pt")) return "pt-PT";
    if (normalized === "en-gb" || normalized.startsWith("en-gb-")) return "en-GB";
    if (normalized.startsWith("en")) return "en";
    if (normalized === "es-419" || normalized.startsWith("es-419-")) return "es-419";
    if (normalized.startsWith("es")) return "es";
    const base = normalized.split("-")[0];
    if (isLanguageCode(base)) return base;
  }

  return "pt";
}

function getBaseLanguage(language: LanguageCode): LanguageCode | null {
  if (language === "pt-PT") return "pt";
  if (language === "en-GB") return "en";
  if (language === "es-419") return "es";
  return null;
}

function getResourceString(language: LanguageCode, key: string): string | undefined {
  const [namespace, ...path] = key.split(".");
  if (!namespace || path.length === 0) return undefined;

  const read = (resource: Resource): string | undefined => {
    let value: unknown = resource[namespace];
    for (const segment of path) {
      if (!value || typeof value !== "object") return undefined;
      value = (value as Record<string, unknown>)[segment];
    }
    return typeof value === "string" ? value : undefined;
  };

  return (
    read(resources[language]) ??
    (getBaseLanguage(language) ? read(resources[getBaseLanguage(language)!]) : undefined) ??
    read(resources.en)
  );
}

type I18nContextValue = {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  isRTL: boolean;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(detectLanguage);

  const setLanguage = useCallback((nextLanguage: LanguageCode) => {
    setLanguageState(nextLanguage);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch {
      // The UI remains usable without persistent storage.
    }
  }, []);

  useEffect(() => {
    const isRTL = language === "ar";
    document.documentElement.lang = language;
    document.documentElement.dir = isRTL ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      isRTL: language === "ar",
      t: (key, fallback) =>
        siteCopy[language]?.[key.replace("site.", "")] ??
        (getBaseLanguage(language) ? siteCopy[getBaseLanguage(language)!]?.[key.replace("site.", "")] : undefined) ??
        getResourceString(language, key) ??
        fallback ??
        key,
    }),
    [language, setLanguage],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}

export const useSiteI18n = useI18n;
